/**
 * Normalizes voice query and removes spoken Hindi/Hinglish fillers
 */
export function normalizeVoiceQuery(query = '') {
  if (!query || typeof query !== 'string') return ''

  let clean = query.trim().toLowerCase()

  // Remove common punctuation from speech recognition transcripts
  clean = clean.replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?"'।]/g, ' ')

  // Remove common filler spoken phrases in Hindi / Hinglish
  const fillers = [
    /kahan milega/gi,
    /kahan milegi/gi,
    /kahan milta hai/gi,
    /kahan milti hai/gi,
    /chahiye/gi,
    /chahiyen/gi,
    /dikhao/gi,
    /dikhaye/gi,
    /dikhao ji/gi,
    /ki dukan/gi,
    /ki dukaan/gi,
    /ki shop/gi,
    /wala/gi,
    /wali/gi,
    /wale/gi,
    /as pas/gi,
    /aas paas/gi,
    /nearby/gi,
    /near me/gi,
    /find me/gi,
    /show me/gi,
    /where to get/gi,
    /i want/gi,
    /please give/gi,
    /kripya/gi,
    /batao/gi,
    /bataiye/gi,
    /चाहिए/gi,
    /दिखाओ/gi,
    /दिखाइए/gi,
    /की दुकान/gi,
    /कहाँ मिलेगा/gi,
    /पास में/gi
  ]

  let processed = clean
  for (const pattern of fillers) {
    processed = processed.replace(pattern, ' ')
  }
  processed = processed.replace(/\s+/g, ' ').trim()

  return processed || clean
}

/**
 * Smart search matcher that supports English, Hindi, and Hinglish keywords
 */
export function matchesQueryWithHinglish(product, query) {
  if (!query || !query.trim()) return true

  const rawQuery = query.trim().toLowerCase()
  const normalizedQuery = normalizeVoiceQuery(rawQuery)

  const searchTarget = [
    product.name || '',
    product.category || '',
    product.shop_name || '',
    product.description || ''
  ].join(' ').toLowerCase()

  // 1. Direct substring match on raw or normalized query
  if (searchTarget.includes(rawQuery) || searchTarget.includes(normalizedQuery)) {
    return true
  }

  // 2. Multi-word match: every word in the normalized query should match either directly or via Hinglish mapping
  const words = normalizedQuery.split(' ').filter((w) => w.length > 0)
  if (words.length === 0) return true

  return words.every((word) => {
    // Direct token match
    if (searchTarget.includes(word)) return true

    // Check Hinglish mapping dictionary
    const expansion = HINDI_HINGLISH_MAP[word]
    if (expansion) {
      const expWords = expansion.split(' ')
      return expWords.some((w) => searchTarget.includes(w))
    }

    return false
  })
}
